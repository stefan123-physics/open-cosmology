import type { Course, Page } from "@/lib/content";

/** Auto-inserted footer on every content page: MIT, instructors, source lecture, license. */
export function Credit({ page, course }: { page: Page; course: Course }) {
  if (course.kind === "textbook") return <TextbookCredit page={page} course={course} />;
  if (course.kind === "highschool") return <HighSchoolCredit page={page} />;
  return (
    <footer className="credit" data-noread>
      <h2>Credits and license</h2>
      <p>
        This page is a rewritten explanation based on{" "}
        <a href={page.source.url} target="_blank" rel="noopener noreferrer">
          {page.source.title}
        </a>{" "}
        from MIT {course.ocwNumber} <em>{course.title}</em> ({course.term}), taught by {joinNames(course.instructors)}, published
        on{" "}
        <a href={course.url} target="_blank" rel="noopener noreferrer">
          MIT OpenCourseWare
        </a>{" "}
        under{" "}
        <a href="https://creativecommons.org/licenses/by-nc-sa/4.0/" target="_blank" rel="noopener noreferrer">
          CC BY-NC-SA 4.0
        </a>
        .
      </p>
      {page.source.readings.length > 0 && (
        <p>
          MIT readings used:{" "}
          {page.source.readings.map((r, i) => (
            <span key={i}>
              {i > 0 && "; "}
              {r.url ? (
                <a href={r.url} target="_blank" rel="noopener noreferrer">
                  {r.title}
                </a>
              ) : (
                r.title
              )}
              {r.location && ` (${r.location})`}
            </span>
          ))}
          .
        </p>
      )}
      {page.courtesy.map((c, i) => (
        <p key={i}>{c}</p>
      ))}
      <p>
        MIT and the instructors do not endorse this site. All diagrams and plots on this page are generated by this site.
        This page is licensed {page.license}: you may share and adapt it for non-commercial use with attribution, under the same
        license.
      </p>
    </footer>
  );
}

/** Credits for a page rewritten from an openly licensed textbook (e.g. Ferreras, UCL Press, CC BY-NC 4.0): the
 *  publisher's attribution wording, the licence, and the changes made, as the licence requires. */
function TextbookCredit({ page, course }: { page: Page; course: Course }) {
  return (
    <footer className="credit" data-noread>
      <h2>Credits and license</h2>
      <p>
        This page is a rewritten explanation based on {page.source.title} of {joinNames(course.instructors)},{" "}
        <em>{course.title}</em> ({course.publisher}, {course.term}), an open textbook licensed under{" "}
        <a href={course.licenseUrl} target="_blank" rel="noopener noreferrer">
          {course.license}
        </a>
        . Attribution:{" "}
        <a href={course.url} target="_blank" rel="noopener noreferrer">
          {course.attribution}
        </a>
      </p>
      <p>
        Changes: the text is rewritten in our own words, with our own worked examples; every diagram and plot is generated by
        this site, and figures from other copyright holders in the book are not used.
      </p>
      {page.source.readings.length > 0 && (
        <p>
          Other readings used:{" "}
          {page.source.readings.map((r, i) => (
            <span key={i}>
              {i > 0 && "; "}
              {r.url ? (
                <a href={r.url} target="_blank" rel="noopener noreferrer">
                  {r.title}
                </a>
              ) : (
                r.title
              )}
              {r.location && ` (${r.location})`}
            </span>
          ))}
          .
        </p>
      )}
      {page.courtesy.map((c, i) => (
        <p key={i}>{c}</p>
      ))}
      <p>
        The author and {course.publisher} do not endorse this site. This page is licensed {page.license}: you may share and
        adapt it for non-commercial use with attribution, under the same license.
      </p>
    </footer>
  );
}

/** Credits for a High School lesson: its main source and any other readings. Which sources the High School uses is
 *  still open (docs/HIGHSCHOOL-PLAN.md §7, F-OS); OpenStax may not be used (AGENTS.md, Writing rules 10). */
function HighSchoolCredit({ page }: { page: Page }) {
  const sources = [{ title: page.source.title, url: page.source.url, location: undefined as string | undefined }, ...page.source.readings];
  return (
    <footer className="credit" data-noread>
      <h2>Credits and license</h2>
      <p>
        This High School lesson is written in our own words from:{" "}
        {sources.map((r, i) => (
          <span key={i}>
            {i > 0 && "; "}
            {r.url ? (
              <a href={r.url} target="_blank" rel="noopener noreferrer">
                {r.title}
              </a>
            ) : (
              r.title
            )}
            {r.location && ` (${r.location})`}
          </span>
        ))}
        .
      </p>
      {page.courtesy.map((c, i) => (
        <p key={i}>{c}</p>
      ))}
      <p>
        The authors of these sources do not endorse this site. All diagrams and plots on this page are generated by this site.
        This page is licensed {page.license}: you may share and adapt it for non-commercial use with attribution, under the same
        license.
      </p>
    </footer>
  );
}

function joinNames(names: string[]) {
  if (names.length <= 1) return names.join("");
  return names.slice(0, -1).join(", ") + " and " + names[names.length - 1];
}
